import {CANONICAL_ADMISSION_SUPERSESSION_CONFIRMATION,CanonicalAdmissionSupersessionService} from "../packages/mercury/index.js";
import {assertAllowedArgs,createCanonicalOperatorRuntime,parseArgs} from "./mercury-canonical-admission-runtime.mjs";

const args=parseArgs(process.argv.slice(2));
assertAllowedArgs(args,["--authorization-id","--confirm","--requested-by","--reason","--ttl-minutes","--evidence-state","--historical-state","--decision-state","--observation-state","--authorization-state"]);
const result=await new CanonicalAdmissionSupersessionService(createCanonicalOperatorRuntime(args)).supersede({authorizationId:args.get("--authorization-id"),confirmation:args.get("--confirm"),requestedBy:args.get("--requested-by"),reason:args.get("--reason"),ttlMinutes:args.has("--ttl-minutes")?Number(args.get("--ttl-minutes")):15});
const authorization=result.authorization;
console.log("EXPIRED CANONICAL ADMISSION AUTHORIZATION SUPERSESSION");
console.log("");
console.log("Predecessor authorization: ",authorization.lineage.predecessorAuthorizationId);
console.log("Successor authorization:   ",authorization.authorizationId);
console.log("Lineage root:              ",authorization.lineage.rootAuthorizationId);
console.log("Generation:                ",authorization.lineage.generation);
console.log("Binding relationship:      ",authorization.lineage.bindingChange);
console.log("Previous assessment:       ",authorization.lineage.predecessorAssessmentId);
console.log("Current assessment:        ",authorization.assessmentId);
console.log("Previous binding digest:   ",authorization.lineage.predecessorCandidateBindingDigest);
console.log("Current binding digest:    ",authorization.candidateBindingDigest);
console.log("Status:                    ",result.status);
console.log("Expires at:                ",authorization.expiresAt);
console.log("Canonical admission:        NOT EXECUTED");
