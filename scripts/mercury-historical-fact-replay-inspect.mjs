import { readFile } from "node:fs/promises";
import path from "node:path";
import { validateHistoricalFactReplayPlan } from "../packages/mercury/index.js";
import { parseHistoricalFactReplayArgs } from "./mercury-historical-fact-replay-runtime.mjs";

const args = parseHistoricalFactReplayArgs(process.argv.slice(2));
for (const key of args.keys()) if (key !== "--plan") throw new Error(`HISTORICAL_FACT_REPLAY_ARGUMENT_NOT_ALLOWED:${key}`);
const planPath = path.resolve(String(args.get("--plan") || ".forge-review/mercury/historical-fact-replay-plan.json"));
const plan = JSON.parse(await readFile(planPath, "utf8"));
const report = validateHistoricalFactReplayPlan(plan);
if (!report.valid) throw new Error(`HISTORICAL_FACT_REPLAY_PLAN_INVALID:${report.errors.join(",")}`);
console.log("HISTORICAL FACT REPLAY INSPECT");
console.log("Replay plan:              ", plan.replayPlanId);
console.log("Binding digest:           ", plan.bindingDigest);
console.log("Policy:                   ", plan.factPolicyVersion);
console.log("Prepared at:              ", plan.preparedAt);
for (const source of plan.sourceCohorts) console.log(`${source.sourceId}:`, `retained=${source.retainedCount} eligible=${source.factEligibleCount} new=${source.newFactCount} duplicate=${source.duplicateCount} blocked=${source.blockedCount}`);
console.log("Combined NEW_FACT:        ", plan.counts.newFacts);
console.log("Execution authorized:     ", plan.authority.executionAuthorized);
console.log("Historical admission:     ", plan.authority.historicalAdmissionPerformed);
console.log("Current Price eligible:   ", plan.authority.currentPriceEligible);
console.log("Cheapest eligible:        ", plan.authority.cheapestEligible);
console.log("Pick eligible:            ", plan.authority.pickEligible);
console.log("Publication eligible:     ", plan.authority.publicationEligible);
console.log("Provider calls:           ", plan.authority.providerCallsRequired);
console.log("Paid tasks:               ", plan.authority.paidTasksRequired);
console.log("Actual spend:             $0.000");
console.log("");
for (const entry of plan.inventory) console.log(`${entry.classification}: ${entry.evidenceId} -> ${entry.expectedHistoricalObservationId ?? "NONE"}${entry.reason ? ` (${entry.reason})` : ""}`);
